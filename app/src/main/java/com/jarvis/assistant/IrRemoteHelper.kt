// \u0645\u0644\u0627\u062D\u0638\u0629 \u0645\u0647\u0645\u0629: \u0623\u063A\u0644\u0628 \u0627\u0644\u0647\u0648\u0627\u062A\u0641 \u0627\u0644\u062D\u062F\u064A\u062B\u0629 \u0645\u0627\u0639\u0627\u062F\u0634 \u0641\u064A\u0647\u0627 \u0645\u0631\u0633\u0644 IR \u0641\u064A\u0632\u064A\u0642\u064A \u2014 \u0647\u0630\u0647 \u0627\u0644\u0645\u064A\u0632\u0629 \u062A\u062E\u062F\u0645 \u0641\u0642\u0637 \u0639\u0644\u0649 \u0627\u0644\u0623\u062C\u0647\u0632\u0629 \u0627\u0644\u0644\u064A \u0639\u0646\u062F\u0647\u0627 \u0647\u0627\u0644\u0642\u0637\u0639\u0629 (\u0623\u063A\u0644\u0628 \u0647\u0648\u0627\u062A\u0641 Xiaomi/\u0628\u0639\u0636 \u0627\u0644\u0635\u064A\u0646\u064A\u0629 \u0645\u062A\u0648\u0641\u0631\u0629)
class IrRemoteHelper(context: Context) {

    private val irManager: ConsumerIrManager? =
        context.getSystemService(Context.CONSUMER_IR_SERVICE) as? ConsumerIrManager

    fun hasIrBlaster(): Boolean {
        return irManager?.hasIrEmitter() == true
    }

    // \u0645\u0648\u062C\u0627\u062A IR \u0634\u0627\u0626\u0639\u0629 \u062C\u0627\u0647\u0632\u0629 (\u062A\u0631\u062F\u062F\u0627\u062A \u0628\u0627\u0644\u0647\u064A\u0631\u062A\u0632) \u0644\u0623\u0632\u0631\u0627\u0631 \u062A\u0644\u0641\u0632\u064A\u0648\u0646 \u0634\u0627\u0626\u0639\u0629 \u0643\u0645\u062B\u0627\u0644 \u0623\u0648\u0644\u064A \u0644\u0644\u062A\u062C\u0631\u0628\u0629
    // \u0627\u0644\u0645\u0633\u062A\u062E\u062F\u0645 \u064A\u0642\u062F\u0631 \u064A\u0632\u064A\u062F/\u064A\u0639\u062F\u0651\u0644 \u0631\u0645\u0648\u0632 \u062D\u0642\u064A\u0642\u064A\u0629 \u0645\u0637\u0627\u0628\u0642\u0629 \u0644\u062C\u0647\u0627\u0632\u0647
    fun sendPowerToggle(): Boolean = sendPattern(38000, longArrayOf(9000, 4500, 560, 560, 560, 1690, 560, 39000))

    fun sendVolumeUp(): Boolean = sendPattern(38000, longArrayOf(9000, 4500, 560, 1690, 560, 560, 560, 39000))

    fun sendVolumeDown(): Boolean = sendPattern(38000, longArrayOf(9000, 4500, 560, 560, 1690, 560, 560, 39000))

    // \u062A\u0631\u0633\u0644 \u0646\u0645\u0637 IR \u0645\u062E\u0635\u0635 \u0628\u062A\u0631\u062F\u062F \u0648\u0646\u0645\u0637 \u0632\u0645\u0646\u064A \u0645\u062D\u062F\u062F \u064A\u062F\u062E\u0644\u0647 \u0627\u0644\u0645\u0633\u062A\u062E\u062F\u0645 (\u0645\u0646 \u062C\u0647\u0627\u0632 \u0631\u064A\u0645\u0648\u062A \u0623\u0635\u0644\u064A \u0645\u062B\u0644\u0627\u064B \u0639\u0628\u0631 \u062A\u0637\u0628\u064A\u0642 \u062A\u0633\u062C\u064A\u0644 IR)
    fun sendCustomPattern(frequency: Int, pattern: LongArray): Boolean = sendPattern(frequency, pattern)

    private fun sendPattern(frequency: Int, pattern: LongArray): Boolean {
        if (!hasIrBlaster()) return false
        return try {
            irManager?.transmit(frequency, pattern.map { it.toInt() }.toIntArray())
            true
        } catch (e: Exception) {
            false
        }
    }
}
